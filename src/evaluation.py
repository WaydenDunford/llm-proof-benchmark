"""Prepare blind manual-evaluation bundles and import human judgments.

This module deliberately makes no network request and loads no evaluator model.
"""
from datetime import datetime, timezone
import json
from pathlib import Path
import random
from .schemas import (BenchmarkConfig, Evaluation, EvaluationRecord, ImportedEvaluationFile,
                      RunResult)
from .utils import atomic_text, load_config, save_result

RUBRIC = {
    "assumption_handling": "0 = assumptions ignored, contradicted, or improperly introduced; 1 = partially handled; 2 = all relevant assumptions are correctly handled.",
    "logical_correctness": "0 = major invalid reasoning; 1 = partially correct with nontrivial gaps; 2 = logically correct.",
    "completeness": "0 = proof fails to establish the theorem; 1 = mostly complete with missing justification; 2 = complete proof.",
    "mathematical_rigor": "0 = mathematically weak or incorrect; 1 = acceptable but informal or insufficiently justified; 2 = rigorous enough for the stated level.",
    "clarity": "0 = difficult to follow; 1 = understandable but unclear in places; 2 = clear and well structured.",
}


def _paths(root: Path, result: RunResult) -> tuple[Path, Path, Path]:
    stem = f"{result.theorem.id}_{result.run_id}"
    return (root / "results/evaluation_maps" / f"{stem}_mapping.json",
            root / "results/evaluation_input" / f"{stem}_evaluation_bundle.md",
            root / "results/evaluation_input" / f"{stem}_evaluation_bundle.json")


def _candidates(result: RunResult):
    return [response for response in result.responses if response.status == "success" and response.proof]


def create_mapping(root: Path, raw_path: Path) -> tuple[RunResult, dict, Path]:
    """Assign proof IDs locally; never add identity data to the upload bundle."""
    result = RunResult.model_validate_json(raw_path.read_text(encoding="utf-8"))
    config = load_config(root / "configs/benchmark.yaml", BenchmarkConfig).evaluation
    candidates = _candidates(result)
    if not candidates:
        raise ValueError("The run has no successful proofs to evaluate")
    if config.randomize_proof_order:
        random.Random(config.random_seed).shuffle(candidates)
    mapping = {}
    for number, response in enumerate(candidates, 1):
        proof_id = f"P{number:03d}"
        mapping[proof_id] = {"response_id": response.response_id, "model_name": response.model_name,
                             "model_id": response.model_id, "repetition": response.repetition}
    map_path, _, _ = _paths(root, result)
    payload = {"schema_version": "1.0", "run_id": result.run_id, "theorem_id": result.theorem.id,
               "created_at": datetime.now(timezone.utc).isoformat(),
               "prompt_version": config.prompt_version, "blind": config.blind,
               "randomized": config.randomize_proof_order, "random_seed": config.random_seed,
               "proof_mapping": mapping}
    atomic_text(map_path, json.dumps(payload, indent=2, ensure_ascii=False) + "\n")
    return result, payload, map_path


def _bundle_payload(result: RunResult, mapping: dict, include_reference_proof: bool) -> dict:
    by_id = {response.response_id: response for response in result.responses}
    theorem = {"title": result.theorem.title, "statement": result.theorem.statement,
               "assumptions": result.theorem.assumptions, "allowed_context": result.theorem.allowed_context}
    if include_reference_proof and result.theorem.reference_proof:
        theorem["reference_proof"] = result.theorem.reference_proof
    return {"bundle_type": "manual_chatgpt_proof_evaluation", "prompt_version": mapping["prompt_version"],
            "run_id": result.run_id, "theorem_id": result.theorem.id, "theorem": theorem,
            "rubric": RUBRIC,
            "proofs": [{"proof_id": proof_id, "proof": by_id[data["response_id"]].proof}
                       for proof_id, data in mapping["proof_mapping"].items()]}


def _bullets(items: list[str]) -> str:
    return "\n".join(f"- {item}" for item in items) or "- None provided."


def bundle_markdown(bundle: dict) -> str:
    theorem = bundle["theorem"]
    parts = ["# LLM Proof Evaluation Task", f"Evaluation template version: `{bundle['prompt_version']}`", "## Instructions",
        "You are evaluating mathematical proofs generated by anonymous language models. Do not infer or guess which model produced each proof. Evaluate each proof independently. The theorem and assumptions are authoritative. Do not reward verbosity or style unless it improves clarity. Focus primarily on mathematical validity.",
        "## Theorem", "### Title", theorem["title"], "### Statement", theorem["statement"], "### Assumptions", _bullets(theorem["assumptions"]), "### Allowed context", _bullets(theorem["allowed_context"])]
    if "reference_proof" in theorem:
        parts += ["### Reference proof", theorem["reference_proof"]]
    parts += ["## Evaluation rubric", "Score each category from 0 to 2. Total score: 0–10."]
    for number, (name, description) in enumerate(RUBRIC.items(), 1):
        parts += [f"### {number}. {name.replace('_', ' ').title()}", description]
    parts += ["## Required verdict", "Choose exactly one: `correct`, `mostly_correct`, `flawed`, `incorrect`.", "## Additional required fields", "For every proof return proof_id, all five scores, total_score, verdict, first_error_step, critical_issues, strengths, and evaluator_comment. If there is no identifiable error step, set first_error_step to null."]
    for proof in bundle["proofs"]:
        parts += [f"## Proof {proof['proof_id']}", proof["proof"], "---"]
    required = {"run_id": bundle["run_id"], "theorem_id": bundle["theorem_id"], "evaluator_id": "chatgpt_plus_run_1", "prompt_version": bundle["prompt_version"], "evaluations": [{"proof_id": "P001", "scores": {key: 0 for key in RUBRIC}, "total_score": 0, "verdict": "incorrect", "first_error_step": None, "critical_issues": [], "strengths": [], "evaluator_comment": ""}]}
    parts += ["## REQUIRED OUTPUT FORMAT", "Return ONLY valid JSON. Do not include Markdown fences. Do not include explanatory text before or after the JSON.", "Use this exact structure:", "```json", json.dumps(required, indent=2), "```", "All five scores must be integers from 0 to 2. total_score must equal their sum. verdict must be one of correct, mostly_correct, flawed, incorrect. Evaluate every proof in the file. Do not omit any proof."]
    return "\n\n".join(parts) + "\n"


def prepare_evaluation(root: Path, raw_path: Path, include_reference_proof: bool = False) -> tuple[Path, Path, Path]:
    result, mapping, map_path = create_mapping(root, raw_path)
    bundle = _bundle_payload(result, mapping, include_reference_proof)
    _, markdown_path, json_path = _paths(root, result)
    atomic_text(markdown_path, bundle_markdown(bundle))
    atomic_text(json_path, json.dumps(bundle, indent=2, ensure_ascii=False) + "\n")
    return markdown_path, json_path, map_path


def _load_mapping(root: Path, result: RunResult) -> dict:
    map_path, _, _ = _paths(root, result)
    if not map_path.exists():
        raise ValueError(f"Blind mapping not found: {map_path}. Run prepare-evaluation first.")
    mapping = json.loads(map_path.read_text(encoding="utf-8"))
    if mapping.get("run_id") != result.run_id or mapping.get("theorem_id") != result.theorem.id:
        raise ValueError("Mapping file does not belong to this benchmark run")
    return mapping


def import_evaluation(root: Path, raw_path: Path, evaluation_path: Path) -> Path:
    """Validate a manual JSON response, reconnect IDs locally, then report."""
    result = RunResult.model_validate_json(raw_path.read_text(encoding="utf-8"))
    # utf-8-sig also accepts ordinary UTF-8, while accepting JSON saved by
    # Windows PowerShell versions that prefix a UTF-8 BOM.
    imported = ImportedEvaluationFile.model_validate_json(evaluation_path.read_text(encoding="utf-8-sig"))
    mapping = _load_mapping(root, result)
    expected = set(mapping["proof_mapping"])
    received = {item.proof_id for item in imported.evaluations}
    if imported.run_id != result.run_id or imported.theorem_id != result.theorem.id:
        raise ValueError("Evaluation run_id or theorem_id does not match the raw result")
    if received != expected:
        missing, unknown = expected - received, received - expected
        raise ValueError(f"Evaluation proof IDs do not match mapping (missing={sorted(missing)}, unknown={sorted(unknown)})")
    by_response = {response.response_id: response for response in result.responses}
    result.anonymous_mapping = {proof_id: info["response_id"] for proof_id, info in mapping["proof_mapping"].items()}
    result.evaluations = []
    result.models = []
    for item in imported.evaluations:
        info = mapping["proof_mapping"][item.proof_id]
        if info["response_id"] not in by_response:
            raise ValueError(f"Mapping points to a response absent from raw results: {item.proof_id}")
        evaluation = Evaluation(anonymous_proof_id=item.proof_id, scores=item.scores,
                                global_score=item.total_score, verdict=item.verdict,
                                first_error_step=item.first_error_step,
                                critical_issues=item.critical_issues, strengths=item.strengths,
                                evaluator_comment=item.evaluator_comment)
        result.evaluations.append(EvaluationRecord(anonymous_proof_id=item.proof_id, status="success", evaluation=evaluation))
        response = by_response[info["response_id"]]
        result.models.append({"proof_id": item.proof_id, "model_name": response.model_name,
                              "model_id": response.model_id, "proof": response.proof,
                              "evaluation": item.model_dump()})
    metadata = {"evaluator_id": imported.evaluator_id, "prompt_version": imported.prompt_version,
                "mode": "manual_chatgpt", "imported_at": datetime.now(timezone.utc).isoformat(),
                "source_file": evaluation_path.name, "proof_count": len(imported.evaluations)}
    result.evaluator = metadata
    result.evaluation_imports.append(metadata)
    target = root / "results/evaluated" / f"{result.theorem.id}_{result.run_id}_evaluated.json"
    save_result(target, result)
    from .reporting import generate_reports
    generate_reports(target)
    return target
